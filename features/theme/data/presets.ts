/**
 * The preset catalogue — fourteen bundles of design decisions, not fourteen palettes.
 *
 * A preset commits across seven axes at once: neutral temperature, chroma
 * budget, radius strategy, border-versus-shadow policy, type pairing, density
 * and motion model. That is deliberate. A picker whose entries differ only in
 * hue gives the person choosing it one real decision dressed up as fourteen,
 * and every project built from it looks like the same project in a different
 * colour. Two presets here may share a hue; none share a posture.
 *
 * Each mode is authored independently rather than inverted. Light-mode text
 * sits near L 0.24 / 0.52 / 0.63 while dark-mode text sits near 0.94 / 0.845 /
 * 0.76 — dark mode has less than half the tonal room, so an inverted light
 * palette lands its secondary text either invisible or shouting. The hue is
 * shared, the lightness is re-decided, and chroma comes down 12–18% in dark
 * because the same chroma glows against a dark ground.
 *
 * Deliberately does not: hold radius (that is `shape`, four independent
 * tokens), resolve a theme (the editor merges the user's overrides over these),
 * or name a font the generated project must license — every family here is on
 * Google Fonts. Values are checked in tests/theme-presets.test.ts against APCA
 * floors; a preset that fails is wrong, and the floor is not.
 */

import type {
  elevationStrategyValues,
  motionModelValues,
} from "@/types/project"

export type Preset = {
  id: string
  /** a place or an object — never an adjective, because adjectives are what presets are trying not to be */
  name: string
  /** one line, concrete, shown under the name in the picker */
  character: string
  /** the three or four commitments that make it recognisable */
  axes: string[]
  /** real families, all on Google Fonts */
  fonts: { display: string; body: string; mono: string }
  scaleRatio: number
  shape: { control: number; card: number; overlay: number; pill: boolean }
  density: "compact" | "comfortable" | "spacious"
  elevationStrategy: (typeof elevationStrategyValues)[number]
  motionModel: (typeof motionModelValues)[number]
  neutralHue: number
  vividness: number
  /** the full shadcn token set as oklch strings, keyed without the leading `--` */
  light: Record<string, string>
  dark: Record<string, string>
  /** how to describe this preset to a build agent: values, not adjectives */
  promptDetails: string
}

